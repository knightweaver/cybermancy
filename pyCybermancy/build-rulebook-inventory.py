RE_HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*$", re.MULTILINE)
RE_MD_IMAGE = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)(?:\s+[\"'][^\"']*[\"'])?\)")
RE_MD_LINK = re.compile(r"(?<!!)\[([^\]]+)\]\(([^)\s]+)(?:\s+[\"'][^\"']*[\"'])?\)")
RE_HTML_IMG = re.compile(r"<img\b[^>]*?\bsrc\s*=\s*[\"']([^\"']+)[\"'][^>]*>", re.I)
RE_HTML_LINK = re.compile(r"<a\b[^>]*?\bhref\s*=\s*[\"']([^\"']+)[\"'][^>]*>", re.I)
RE_HTML_TAG = re.compile(r"</?[A-Za-z][^>]*>")
RE_SNIPPET = re.compile(r"--8<--\s*[\"']([^\"']+)[\"']")
RE_JINJA_EXPR = re.compile(r"{{.*?}}", re.S)
RE_JINJA_STMT = re.compile(r"{%.*?%}", re.S)
RE_LOAD_CSV = re.compile(r"\bload_csv\s*\(\s*[\"']([^\"']+)[\"']")
# Match the actual include-markdown plugin syntax; do not treat prose like
# "may include: Environmental Events" as an include directive.
RE_INCLUDE_MD = re.compile(
    r"""{%\s*include-markdown\s+["']([^"']+)["'][^%]*%}""",
    re.I | re.S,
)
RE_ADMONITION = re.compile(r"^\s*(?:!!!|\?\?\?)\s+", re.MULTILINE)
RE_TABS = re.compile(r'^\s*===\s+["\']', re.MULTILINE)
RE_ATTR_LIST = re.compile(r"\{[^{}]*(?:\.|#|:)[^{}]*\}")
RE_GENERATED = re.compile(
    r"\b(?:auto[- ]?generated|generated by|do not edit|do not modify|generator-owned|generated file)\b",
    re.I,
)
RE_GENERATOR_OWNER = re.compile(r"(?:generated by|generator)\s*[:=-]?\s*`?([^\n`]+)", re.I)
RE_MKDOCS_MD_PATH = re.compile(r"(?P<path>[A-Za-z0-9_./ -]+\.md)\b")
RE_RAW_URL = re.compile(r"https?://[^\s<>)\]}]+", re.I)
RE_DOCS_DIR = re.compile(r"^\s*docs_dir\s*:\s*[\"']?([^\"'#\n]+)", re.M)
RE_WORD = re.compile(r"\b[\w’'-]+\b", re.UNICODE)

