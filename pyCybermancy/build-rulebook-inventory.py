#!/usr/bin/env python3
"""Cybermancy rulebook source inventory builder.

Phase 1 repository scanner for the Cybermancy rulebook publishing pipeline.

This scanner is deliberately read-only. It inventories source files, MkDocs
publication scope, generated documentation, print-normalization concerns,
dependencies, and generator/source drift. It does NOT decide canon authority
or rulebook inclusion; those remain Phase 2 editorial decisions.

Run from the Cybermancy repository root:
    python pyCybermancy/build-rulebook-inventory.py

Or:
    python pyCybermancy/build-rulebook-inventory.py --repo-root /path/to/cybermancy
"""

